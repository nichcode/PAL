local function cmakeBool(val)
    return val and "ON" or "OFF"
end

local function generateCMakeLists()
    print("\n=======================================================")
    print("Generating CMakeLists.txt")

    local file = io.open("CMakeLists.txt", "w")
    if not file then
        print("Failed to write to CMakeLists.txt")
        return
    end

    local content = string.format([[# Auto-generated by Premake5 (`premake5 cmake`). Do not edit manually.
cmake_minimum_required(VERSION 3.16)
project(PAL2 LANGUAGES C)

set(CMAKE_C_STANDARD 99)
set(CMAKE_C_STANDARD_REQUIRED ON)

# ==============================================================================
# Build Options (synced from pal_config.lua)
# ==============================================================================
option(PAL_BUILD_STATIC          "Build PAL as a static library" %s)
option(PAL_BUILD_EVENT_MODULE    "Build event module"            %s)
option(PAL_BUILD_SYSTEM_MODULE   "Build system module"           %s)
option(PAL_BUILD_THREAD_MODULE   "Build thread module"           %s)
option(PAL_BUILD_VIDEO_MODULE    "Build video module"            %s)
option(PAL_BUILD_OPENGL_MODULE   "Build opengl module"           %s)
option(PAL_BUILD_GRAPHICS_MODULE "Build graphics module"         %s)

# ==============================================================================
# Core Sources
# ==============================================================================
file(GLOB PAL_SOURCES
    "${CMAKE_CURRENT_SOURCE_DIR}/src/*.c"
    "${CMAKE_CURRENT_SOURCE_DIR}/src/core/*.c"
)

set(PAL_PRIVATE_LIBS "")
set(PAL_PRIVATE_DEFINES "")
set(PAL_PUBLIC_DEFINES "")

if(MSVC)
    list(APPEND PAL_PRIVATE_DEFINES _CRT_SECURE_NO_WARNINGS)
endif()

if(WIN32)
    file(GLOB PAL_CORE_WIN32 "${CMAKE_CURRENT_SOURCE_DIR}/src/core/win32/*.c")
    list(APPEND PAL_SOURCES ${PAL_CORE_WIN32})
elseif(UNIX AND NOT APPLE)
    file(GLOB PAL_CORE_POSIX "${CMAKE_CURRENT_SOURCE_DIR}/src/core/posix/*.c")
    list(APPEND PAL_SOURCES ${PAL_CORE_POSIX})
    list(APPEND PAL_PRIVATE_LIBS dl)
endif()

# ==============================================================================
# Optional Modules
# ==============================================================================
if(PAL_BUILD_EVENT_MODULE)
    file(GLOB PAL_EVENT_SOURCES "${CMAKE_CURRENT_SOURCE_DIR}/src/event/*.c")
    list(APPEND PAL_SOURCES ${PAL_EVENT_SOURCES})
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_EVENT_MODULE=1)
else()
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_EVENT_MODULE=0)
endif()

if(PAL_BUILD_SYSTEM_MODULE)
    file(GLOB PAL_SYSTEM_SOURCES "${CMAKE_CURRENT_SOURCE_DIR}/src/system/*.c")
    list(APPEND PAL_SOURCES ${PAL_SYSTEM_SOURCES})

    if(WIN32)
        file(GLOB PAL_SYSTEM_WIN32 "${CMAKE_CURRENT_SOURCE_DIR}/src/system/win32/*.c")
        list(APPEND PAL_SOURCES ${PAL_SYSTEM_WIN32})
    elseif(UNIX AND NOT APPLE)
        file(GLOB PAL_SYSTEM_LINUX "${CMAKE_CURRENT_SOURCE_DIR}/src/system/linux/*.c")
        list(APPEND PAL_SOURCES ${PAL_SYSTEM_LINUX})
    endif()

    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_SYSTEM_MODULE=1)
else()
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_SYSTEM_MODULE=0)
endif()

if(PAL_BUILD_THREAD_MODULE)
    file(GLOB PAL_THREAD_SOURCES "${CMAKE_CURRENT_SOURCE_DIR}/src/thread/*.c")
    list(APPEND PAL_SOURCES ${PAL_THREAD_SOURCES})

    if(WIN32)
        file(GLOB PAL_THREAD_WIN32 "${CMAKE_CURRENT_SOURCE_DIR}/src/thread/win32/*.c")
        list(APPEND PAL_SOURCES ${PAL_THREAD_WIN32})
    elseif(UNIX AND NOT APPLE)
        file(GLOB PAL_THREAD_POSIX "${CMAKE_CURRENT_SOURCE_DIR}/src/thread/posix/*.c")
        list(APPEND PAL_SOURCES ${PAL_THREAD_POSIX})
        list(APPEND PAL_PRIVATE_LIBS pthread)
    endif()

    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_THREAD_MODULE=1)
else()
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_THREAD_MODULE=0)
endif()

if(PAL_BUILD_VIDEO_MODULE)
    file(GLOB PAL_VIDEO_SOURCES "${CMAKE_CURRENT_SOURCE_DIR}/src/video/*.c")
    list(APPEND PAL_SOURCES ${PAL_VIDEO_SOURCES})

    if(WIN32)
        file(GLOB PAL_VIDEO_WIN32 "${CMAKE_CURRENT_SOURCE_DIR}/src/video/win32/*.c")
        list(APPEND PAL_SOURCES ${PAL_VIDEO_WIN32})
        list(APPEND PAL_PRIVATE_LIBS user32 gdi32)
    elseif(UNIX AND NOT APPLE)
        include(CheckIncludeFile)

        check_include_file("wayland-client.h" PAL_FOUND_WAYLAND)
        if(PAL_FOUND_WAYLAND)
            file(GLOB PAL_VIDEO_WAYLAND "${CMAKE_CURRENT_SOURCE_DIR}/src/video/wayland/*.c")
            list(APPEND PAL_SOURCES ${PAL_VIDEO_WAYLAND})
            list(APPEND PAL_PRIVATE_DEFINES PAL_HAS_WAYLAND_BACKEND=1)
            list(APPEND PAL_PRIVATE_LIBS wayland-client)
        else()
            list(APPEND PAL_PRIVATE_DEFINES PAL_HAS_WAYLAND_BACKEND=0)
        endif()

        check_include_file("X11/Xlib.h" PAL_FOUND_X11)
        if(PAL_FOUND_X11)
            file(GLOB PAL_VIDEO_X11 "${CMAKE_CURRENT_SOURCE_DIR}/src/video/x11/*.c")
            list(APPEND PAL_SOURCES ${PAL_VIDEO_X11})
            list(APPEND PAL_PRIVATE_DEFINES PAL_HAS_X11_BACKEND=1)
            list(APPEND PAL_PRIVATE_LIBS X11)
        else()
            list(APPEND PAL_PRIVATE_DEFINES PAL_HAS_X11_BACKEND=0)
        endif()
    endif()

    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_VIDEO_MODULE=1)
else()
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_VIDEO_MODULE=0)
endif()

if(PAL_BUILD_OPENGL_MODULE)
    file(GLOB PAL_OPENGL_SOURCES "${CMAKE_CURRENT_SOURCE_DIR}/src/opengl/*.c")
    list(APPEND PAL_SOURCES ${PAL_OPENGL_SOURCES})

    if(WIN32)
        file(GLOB PAL_OPENGL_WGL "${CMAKE_CURRENT_SOURCE_DIR}/src/opengl/wgl/*.c")
        list(APPEND PAL_SOURCES ${PAL_OPENGL_WGL})
        list(APPEND PAL_PRIVATE_LIBS opengl32 gdi32 user32)
    elseif(UNIX AND NOT APPLE)
        file(GLOB PAL_OPENGL_EGL "${CMAKE_CURRENT_SOURCE_DIR}/src/opengl/egl/*.c")
        list(APPEND PAL_SOURCES ${PAL_OPENGL_EGL})
        list(APPEND PAL_PRIVATE_LIBS EGL)
    endif()

    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_OPENGL_MODULE=1)
else()
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_OPENGL_MODULE=0)
endif()

if(PAL_BUILD_GRAPHICS_MODULE)
    file(GLOB PAL_GRAPHICS_SOURCES "${CMAKE_CURRENT_SOURCE_DIR}/src/graphics/*.c")
    list(APPEND PAL_SOURCES ${PAL_GRAPHICS_SOURCES})

    if(WIN32)
        file(GLOB PAL_GRAPHICS_WIN32 "${CMAKE_CURRENT_SOURCE_DIR}/src/graphics/win32/*.c")
        list(APPEND PAL_SOURCES ${PAL_GRAPHICS_WIN32})
    elseif(UNIX AND NOT APPLE)
        file(GLOB PAL_GRAPHICS_LINUX "${CMAKE_CURRENT_SOURCE_DIR}/src/graphics/linux/*.c")
        list(APPEND PAL_SOURCES ${PAL_GRAPHICS_LINUX})
    endif()

    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_GRAPHICS_MODULE=1)
else()
    list(APPEND PAL_PUBLIC_DEFINES PAL_HAS_GRAPHICS_MODULE=0)
endif()

# ==============================================================================
# Target Definition
# ==============================================================================
if(PAL_BUILD_STATIC)
    add_library(PAL2 STATIC ${PAL_SOURCES})
else()
    add_library(PAL2 SHARED ${PAL_SOURCES})
    list(APPEND PAL_PUBLIC_DEFINES PAL_EXPORT)
    list(APPEND PAL_PRIVATE_DEFINES PAL_BUILD_DLL)
endif()

set_target_properties(PAL2 PROPERTIES
    C_VISIBILITY_PRESET hidden
)

target_include_directories(PAL2
    PUBLIC  "${CMAKE_CURRENT_SOURCE_DIR}/include"
    PRIVATE "${CMAKE_CURRENT_SOURCE_DIR}/src"
)

target_compile_definitions(PAL2
    PUBLIC  ${PAL_PUBLIC_DEFINES}
    PRIVATE ${PAL_PRIVATE_DEFINES}
)

target_link_libraries(PAL2 PRIVATE ${PAL_PRIVATE_LIBS})
]],
        cmakeBool(PAL_BUILD_STATIC),
        cmakeBool(PAL_BUILD_EVENT_MODULE),
        cmakeBool(PAL_BUILD_SYSTEM_MODULE),
        cmakeBool(PAL_BUILD_THREAD_MODULE),
        cmakeBool(PAL_BUILD_VIDEO_MODULE),
        cmakeBool(PAL_BUILD_OPENGL_MODULE),
        cmakeBool(PAL_BUILD_GRAPHICS_MODULE)
    )

    file:write(content)
    file:close()
    print("Successfully generated CMakeLists.txt")
end

newaction {
    trigger = "cmake",
    description = "Generate a standalone CMakeLists.txt for PAL2",
    execute = generateCMakeLists
}